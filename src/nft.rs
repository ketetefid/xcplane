/// Generates a transient [`NftSet::SshPre`] or a final [`NftSet::SshPost`] nft
/// rule for SSH
fn generate_ssh_rule(nftset: &NftSet) -> Result<String, BoxError> {
    let elements: Result<String, BoxError> = match nftset {
        NftSet::SshPre { server } => {
            let ansible_conn = server
                .ansible_conn
                .load_full()
                .ok_or("Couldn't unwrap AnsibleConn in generate_ssh_rule.")?;
            let ansible_port = ansible_conn.ansible_port.ok_or::<BoxError>(
                format!("ansible_port is absent from server {}", server.name).into(),
            )?;

            if ansible_port != server.ssh_port {
                Ok(ansible_port.to_string() + "," + &server.ssh_port.to_string())
            } else {
                Ok(ansible_port.to_string())
            }
        }

        NftSet::SshPost { server } => Ok(server.ssh_port.to_string()),
        _ => Err("Non-matching NftSet in generate_ssh_elements".into()),
    };
    // SshPre & SshPost both are SSH sets, so the rule_name is always "ssh"
    let rule = set_rule_gen("ssh".to_string(), elements?);
    Ok(rule)
}
// =============================================================
/// Creates an nft rule for inbound set which allows incoming connection to a
/// server's inbounds' ports
fn generate_inbound_rule(nftset: &NftSet) -> Result<String, BoxError> {
    let elements: Result<String, BoxError> = match nftset {
        NftSet::Inbound { server } => Ok(server
            .inbounds
            .iter()
            .filter_map(|inb| {
                // Excluding the super inbound
                if inb.port == 0 {
                    None
                } else {
                    Some(inb.port.to_string())
                }
            })
            .collect::<Vec<String>>()
            .join(",")),

        _ => Err("Non-matching NftSet in generate_inbound_elements".into()),
    };

    let rule = set_rule_gen(nftset.to_string(), elements?);
    Ok(rule)
}
