/// Both NftChain and NftSet have the trait of writing their rules
pub trait NftRule {
    fn write_rule(
        self,
        workspace: &WorkSpace,
        server: &KetServer,
    ) -> impl std::future::Future<Output = Result<PathBuf, BoxError>> + Send;
}

/// An enum containing different nftables sets
pub enum NftSet {
    /// Builds the transient nft rule when changing SSH port. At this transient
    /// stage both ansible_port and ssh_port are opened before/during
    /// reconciliation.
    SshPre { server: Arc<KetServer> },

    /// Builds the final SSH nft rule post transition which allows incoming
    /// connection only to ssh_port.
    SshPost { server: Arc<KetServer> },

    /// The set that is used in the inbound rule which allows incoming
    /// connection to the inbounds' ports of a server
    Inbound { server: Arc<KetServer> },

    /// Builds the set for the IPv4 nft rule outblocked4 that blocks new
    /// outbound connection to the list of countries defined for the server in
    /// the cloud config
    OutBlocked4 {
        workspace: Arc<WorkSpace>,
        countries: Vec<CountryCode>,
    },

    /// Builds the set for the IPv6 nft rule outblocked6 that blocks new
    /// outbound connection to the list of countries defined for the server in
    /// the cloud config
    OutBlocked6 {
        workspace: Arc<WorkSpace>,
        countries: Vec<CountryCode>,
    },

    /// The Cloudflare IPv4 set
    Cloudflare4,
    /// The Cloudflare IPv6 set
    Cloudflare6,
}

/// Represents the three major nft chains
#[derive(Display, AsRefStr, Debug, Clone)]
#[strum(serialize_all = "lowercase")]
pub enum NftChain {
    Input,
    Output,
    Forward,
}

