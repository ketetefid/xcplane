/// Creates an nft rule which blocks new outbound connections to the list of
/// countries set in the cloud
async fn generate_blocked_elements(nftset: NftSet) -> Result<String, BoxError> {
    // Since the DB is recreated periodically, reusing an SqlConn is not correct
    // and we needed to reopen the DB
    let rule_name = nftset.to_string();

    let elements: Result<String, BoxError> = match nftset {
        NftSet::OutBlocked4 {
            workspace,
            countries,
        } => {
            let db_file = workspace.dirs.data_dir.join(GEOIP_DB);
            let conn = SqlConn::open(&db_file).await?;

            let sql_holder = iter::repeat("?")
                .take(countries.len())
                .collect::<Vec<_>>()
                .join(",");

            let countries_str = countries.into_iter().map(|c| c.alpha2());

            let elements = conn
                .call(move |conn| {
                    let mut stmt4 = conn.prepare(&format!(
                        "SELECT start, end FROM geoip4 WHERE country IN ({})",
                        sql_holder
                    ))?;

                    let ip4_ranges_res = stmt4.query_map(
                        rusqlite::params_from_iter(countries_str.to_owned()),
                        |row| {
                            let start: String = row.get("start")?;
                            let end: String = row.get("end")?;

                            Ok(start + "-" + &end)
                        },
                    )?;

                    let mut ip4_ranges = Vec::new();

                    for ip_range in ip4_ranges_res {
                        ip4_ranges.push(ip_range?);
                    }

                    Ok::<_, SqlErr>(ip4_ranges.join(",\n    "))
                })
                .await?;

            Ok(elements)
        }
        //////////////////////////////////////////////////////
        NftSet::OutBlocked6 {
            workspace,
            countries,
        } => {
            let db_file = workspace.dirs.data_dir.join(GEOIP_DB);
            let conn = SqlConn::open(&db_file).await?;

            let sql_holder = iter::repeat("?")
                .take(countries.len())
                .collect::<Vec<_>>()
                .join(",");

            let countries_str = countries.into_iter().map(|c| c.alpha2());

            let elements = conn
                .call(move |conn| {
                    let mut stmt6 = conn.prepare(&format!(
                        "SELECT start, end FROM geoip6 WHERE country IN ({})",
                        sql_holder
                    ))?;

                    let ip6_ranges_res =
                        stmt6.query_map(rusqlite::params_from_iter(countries_str), |row| {
                            let start: String = row.get("start")?;
                            let end: String = row.get("end")?;

                            Ok(start + "-" + &end)
                        })?;

                    let mut ip6_ranges = Vec::new();

                    for ip_range in ip6_ranges_res {
                        ip6_ranges.push(ip_range?);
                    }

                    Ok::<_, SqlErr>(ip6_ranges.join(",\n    "))
                })
                .await?;

            Ok(elements)
        }

        _ => Err("Non-matching NftSet in generate_blocked_elements".into()),
    };

    let rule = set_rule_gen(rule_name, elements?);
    Ok(rule)
}
