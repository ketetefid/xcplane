/// Downloads Cloudflare IPv4 or IPv6 ranges and creates a corresponding nft
/// rule
async fn generate_cloudflare_elements(nftset: &NftSet) -> Result<String, BoxError> {
    let elements: Result<String, BoxError> = match nftset {
        NftSet::Cloudflare4 => {
            let cf_ranges4 = reqwest::get("https://www.cloudflare.com/ips-v4/#")
                .await?
                .error_for_status()?
                .text()
                .await?;

            let cf_vec4 = cf_ranges4
                .lines()
                .map(|s| s.to_owned())
                .collect::<Vec<String>>();

            Ok(cf_vec4.join(",\n    "))
        }

        NftSet::Cloudflare6 => {
            let cf_ranges6 = reqwest::get("https://www.cloudflare.com/ips-v6/#")
                .await?
                .error_for_status()?
                .text()
                .await?;

            let cf_vec6 = cf_ranges6
                .lines()
                .map(|s| s.to_owned())
                .collect::<Vec<String>>();

            Ok(cf_vec6.join(",\n    "))
        }

        _ => Err("Non-matching NftSet in generate_cloudflare_elements".into()),
    };

    let rule = set_rule_gen(nftset.to_string(), elements?);
    Ok(rule)
}
