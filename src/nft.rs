/// Creates GeoIP v4/v6 database from the raw bytes of a CSV list
pub async fn create_geoip_db(workspace: &WorkSpace, data: Vec<u8>) -> Result<(), BoxError> {
    #[derive(Deserialize)]
    struct Record {
        start: String,
        end: String,
        country: String,
    }

    let db_file = workspace.dirs.data_dir.join(GEOIP_DB);
    // Delete the old DB first. Because a re-population of DB doesn't take much
    // less than completely recreating the tables, we always rebuild the DB. It
    // will also help to avoid conflicts, stales and duplicates.
    if db_file.exists() {
        // Using std lib provides a faster deletion than tokio::fs in this case
        std::fs::remove_file(&db_file)?;
    }

    let conn = Arc::new(SqlConn::open(&db_file).await?);

    // Wrap the byte buffer in a Cursor to implement std::io::Read
    let cursor = Cursor::new(data);

    // Let the CSV engine read it
    let mut reader = ReaderBuilder::new().has_headers(false).from_reader(cursor);

    conn.clone()
        .call(move |conn| {
            // Performance optimization
            conn.execute_batch(
                "
             PRAGMA journal_mode = MEMORY;
             PRAGMA synchronous = OFF;
             PRAGMA temp_store = MEMORY;
            ",
            )?;
            // Wrapping all the transactions in one commit brings even more
            // performance uplift
            let tx = conn.transaction()?;

            tx.execute_batch(
                "
             CREATE TABLE geoip4 (
		 start   TEXT,
		 end     TEXT,
                 country TEXT NOT NULL,
                 PRIMARY KEY(start, end)
             );

             CREATE TABLE geoip6 (
		 start   TEXT,
		 end     TEXT,
                 country TEXT NOT NULL,
                 PRIMARY KEY(start, end)
             );
             ",
            )?;

            let mut stmt4 = tx.prepare(
                "
             INSERT INTO geoip4 (start, end, country)
             VALUES (?1, ?2, ?3)
             ON CONFLICT(start, end) DO NOTHING
             ",
            )?;

            let mut stmt6 = tx.prepare(
                "
             INSERT INTO geoip6 (start, end, country)
             VALUES (?1, ?2, ?3)
             ON CONFLICT(start, end) DO NOTHING
             ",
            )?;

            for result in reader.deserialize() {
                let record: Record = result.to_sql_err()?;

                match (
                    record.start.parse::<IpAddr>().to_sql_err()?,
                    record.end.parse::<IpAddr>().to_sql_err()?,
                ) {
                    (IpAddr::V4(_), IpAddr::V4(_)) => {
                        stmt4.execute(params![record.start, record.end, record.country])?;
                    }
                    (IpAddr::V6(_), IpAddr::V6(_)) => {
                        stmt6.execute(params![record.start, record.end, record.country])?;
                    }
                    (_, _) => info!(
                        start = record.start,
                        end = record.end,
                        "skipping malformed start & end IPs",
                    ),
                }
            }

            // Creating an index in both tables to make queries faster
            tx.execute_batch(
                "
             CREATE INDEX indx4 ON geoip4(country);
             CREATE INDEX indx6 ON geoip6(country);
             ",
            )?;
            drop(stmt4);
            drop(stmt6);

            tx.commit()?;

            Ok::<_, SqlErr>(())
        })
        .await?;

    Ok(())
}
