/// Takes IPs or a range of IPs in the form of a string element and creates the
/// expression needed for constructing an nft rule
fn set_rule_gen(rule_name: String, elements: String) -> String {
    format!(
        "#!/usr/sbin/nft -f\n\n\
	 # Generated by xcplane\n\
	 # Set: {}\n\
	 # Updated: {}\n\n\
	 flush set inet xcplane {}\n\n\
	 add element inet xcplane {} {{\n    {}\n}}",
        rule_name,
        Utc::now().format("%Y-%m-%d_%H-%M-%S"),
        rule_name,
        rule_name,
        elements
    )
}
