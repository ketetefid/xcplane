/// Downloads the lite GeoIP compressed data from db-ip.com and converts it to a
/// vector of bytes
pub async fn dl_geoip_data() -> Result<Vec<u8>, BoxError> {
    let url = format!(
        "https://download.db-ip.com/free/dbip-country-lite-{}.csv.gz",
        Utc::now().format("%Y-%m")
    );

    let stream_resp = reqwest::get(url)
        .await?
        .error_for_status()?
        .bytes_stream()
        .map_err(std::io::Error::other);

    let reader_source = StreamReader::new(stream_resp);

    let reader = BufReader::new(reader_source);
    let mut decoder = GzipDecoder::new(reader);

    let mut buffer = Vec::new();
    decoder.read_to_end(&mut buffer).await?;

    Ok(buffer)
}
