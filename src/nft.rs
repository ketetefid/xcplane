impl fmt::Display for NftSet {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            NftSet::Cloudflare4 => write!(f, "cloudflare4"),
            NftSet::Cloudflare6 => write!(f, "cloudflare6"),
            NftSet::Inbound { .. } => write!(f, "inbound"),
            NftSet::SshPre { .. } => write!(f, "sshpre"),
            NftSet::SshPost { .. } => write!(f, "sshpost"),
            NftSet::OutBlocked4 { .. } => write!(f, "outblocked4"),
            NftSet::OutBlocked6 { .. } => write!(f, "outblocked6"),
        }
    }
}

impl NftRule for NftSet {
    /// Writes an nft rule for a set operation to disk
    async fn write_rule(
        self,
        workspace: &WorkSpace,
        server: &KetServer,
    ) -> Result<PathBuf, BoxError> {
        let rule_filename = format!("{}/{}.nft", server.name, &self);

        let rule = match self {
            NftSet::Cloudflare4 | NftSet::Cloudflare6 => {
                generate_cloudflare_elements(&self).await?
            }

            NftSet::OutBlocked4 { .. } | NftSet::OutBlocked6 { .. } => {
                generate_blocked_elements(self).await?
            }

            NftSet::SshPre { .. } | NftSet::SshPost { .. } => generate_ssh_rule(&self)?,

            NftSet::Inbound { .. } => generate_inbound_rule(&self)?,
        };

        let rule_path = workspace.dirs.data_dir.join(rule_filename);
        // The server directories might not have been created yet
        if let Some(parent) = rule_path.parent() {
            fs::create_dir_all(parent).await?;
        }

        fs::write(&rule_path, rule).await?;

        Ok(rule_path)
    }
}

impl NftRule for NftChain {
    /// Writes the nft rule for a chain operation
    async fn write_rule(
        self,
        workspace: &WorkSpace,
        server: &KetServer,
    ) -> Result<PathBuf, BoxError> {
        let rule = format!(
            "#!/usr/sbin/nft -f\n\n\
	     # Generated by xcplane\n\
	     # Chain: {}\n\
	     # Updated: {}\n\n\
	     flush chain inet xcplane {}",
            self,
            Utc::now().format("%Y-%m-%d_%H-%M-%S"),
            self,
        );

        let rule_filename = format!("{}/{}.nft", server.name, self);

        let rule_path = workspace.dirs.data_dir.join(rule_filename);
        // The server directories might not have been created yet
        if let Some(parent) = rule_path.parent() {
            fs::create_dir_all(parent).await?;
        }

        fs::write(&rule_path, rule).await?;

        Ok(rule_path)
    }
}
