/// This function prepares whatever nft rule operation needed by a group of
/// AnsibleAction's. Note that:
/// - Not every AnsibleAction needs an accompanying nft operation
/// - xcplane just generates nft operation files but does not directly apply
///   them. The required ones will be picked and used when running Ansible.
pub async fn generate_nftops(
    ansible_actions: &Vec<AnsibleAction>,
    workspace: Arc<WorkSpace>,
    server: Arc<KetServer>,
) -> Result<HashMap<String, PathBuf>, BoxError> {
    let mut ops = HashMap::<String, PathBuf>::new();

    for action in ansible_actions {
        match action {
            AnsibleAction::SSH => {
                let set1 = NftSet::SshPre {
                    server: server.clone(),
                };
                let set2 = NftSet::SshPost {
                    server: server.clone(),
                };
                ops.entry(set1.to_string())
                    .or_insert(set1.write_rule(&workspace, &server).await?);
                ops.entry(set2.to_string())
                    .or_insert(set2.write_rule(&workspace, &server).await?);
            }

            AnsibleAction::FullSetup => {
                let full_set = vec![
                    NftSet::Cloudflare4,
                    NftSet::Cloudflare6,
                    NftSet::OutBlocked4 {
                        workspace: workspace.clone(),
                        countries: server.outbound_block.clone(),
                    },
                    NftSet::OutBlocked6 {
                        workspace: workspace.clone(),
                        countries: server.outbound_block.clone(),
                    },
                    NftSet::Inbound {
                        server: server.clone(),
                    },
                    NftSet::SshPre {
                        server: server.clone(),
                    },
                    NftSet::SshPost {
                        server: server.clone(),
                    },
                ];

                for set in full_set {
                    ops.entry(set.to_string())
                        .or_insert(set.write_rule(&workspace, &server).await?);
                }
            }

            AnsibleAction::DelInbound | AnsibleAction::AddInbound => {
                let set = NftSet::Inbound {
                    server: server.clone(),
                };
                ops.entry(set.to_string())
                    .or_insert(set.write_rule(&workspace, &server).await?);
            }

            AnsibleAction::OutblockedUpdate => {
                let required_sets = vec![
                    NftSet::Cloudflare4,
                    NftSet::Cloudflare6,
                    NftSet::OutBlocked4 {
                        workspace: workspace.clone(),
                        countries: server.outbound_block.clone(),
                    },
                    NftSet::OutBlocked6 {
                        workspace: workspace.clone(),
                        countries: server.outbound_block.clone(),
                    },
                ];

                for set in required_sets {
                    ops.entry(set.to_string())
                        .or_insert(set.write_rule(&workspace, &server).await?);
                }
            }
            _ => {}
        }
    }

    Ok(ops)
}
